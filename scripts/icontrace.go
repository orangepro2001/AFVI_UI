//go:build ignore

// icontrace.go ref.png dx dy out.ts : traces the glyphs of the viewer's tool column from a reference
// image into SVG paths, so that the buttons match the original drawing instead of a look-alike.
//
//	go run scripts/icontrace.go design/reference/right-block-AlignROI-Metal.png 5 6 \
//	    frontend/src/features/workbench/tool-glyphs.ts
//
// For every button the pixels of the 2px rounded border are dropped, the luminance of the rest is
// normalised between the button's background and its brightest pixel, upsampled 8 times with a
// bilinear filter and cut at LEVEL with marching squares; the contours are simplified and written
// as one even-odd path per button, in the coordinates of a 32x32 window that starts at the
// button's integer top-left pixel (the button itself is 30x30 at x 0.7, y 0 of that window).
package main

import (
	"fmt"
	"image"
	_ "image/png"
	"math"
	"os"
	"sort"
	"strconv"
	"strings"
)

const (
	window    = 32   // window edge in pixels
	boxX      = 0.7  // left edge of the 30x30 button inside the window (measured on the reference)
	boxY      = 0.0  // top edge
	boxSize   = 30.0 // outer size of the button
	corner    = 8.0  // corner radius of the button
	ringWidth = 2.45 // how far inside the edge the border still reaches
	scale     = 8    // upsampling factor
	level     = 0.42 // normalised luminance that bounds a glyph
	tolerance = 0.07 // Douglas-Peucker tolerance in pixels

	// Luminance of the button background (#2d2d2f). The most common luminance would be the glyph's
	// own fill for the big filled shapes.
	buttonBackground = 0.299*45 + 0.587*45 + 0.114*47
)

type button struct {
	name string
	// Design coordinates of the button's outer top-left corner (capture offset not applied).
	x, y int
}

var buttons = []button{
	{"select", 1194, 168},
	{"rect", 1194, 231}, {"rectOffset", 1232, 231},
	{"circle", 1194, 268}, {"circleOffset", 1232, 268},
	{"blob", 1194, 305}, {"blobOffset", 1232, 305},
	{"dashedRect", 1194, 369}, {"dashedRectPair", 1232, 369},
	{"dashedCircle", 1194, 406}, {"dashedCirclePair", 1232, 406},
	{"dashedBlob", 1194, 443}, {"dashedBlobPair", 1232, 443},
	{"pipette", 1194, 506}, {"pencil", 1232, 506},
	{"traces", 1194, 569}, {"chip", 1232, 569},
	{"crosshair", 1194, 633},
	{"trash", 1194, 690}, {"save", 1232, 690},
}

type point struct{ x, y float64 }

func main() {
	if len(os.Args) != 5 {
		fmt.Fprintln(os.Stderr, "usage: icontrace ref.png dx dy out.ts")
		os.Exit(2)
	}
	f, err := os.Open(os.Args[1])
	check(err)
	img, _, err := image.Decode(f)
	check(err)
	dx, err := strconv.Atoi(os.Args[2])
	check(err)
	dy, err := strconv.Atoi(os.Args[3])
	check(err)

	var b strings.Builder
	b.WriteString("// Generated by scripts/icontrace.go from design/reference/right-block-AlignROI-Metal.png.\n")
	b.WriteString("// Do not edit by hand: every path is the full outline of one tool glyph (even-odd fill).\n")
	b.WriteString("// Coordinates belong to the viewBox below: the 30x30 button, border included.\n\n")
	b.WriteString("export const GLYPH_VIEW_BOX = '0.7 0 30 30'\n\n")
	b.WriteString("export const toolGlyphs = {\n")
	for _, btn := range buttons {
		path := trace(img, btn.x+dx, btn.y+dy)
		fmt.Fprintf(&b, "  %s:\n    '%s',\n", btn.name, path)
		fmt.Fprintf(os.Stderr, "%-18s %5d bytes\n", btn.name, len(path))
	}
	b.WriteString("} as const\n\n")
	b.WriteString("export type ToolGlyph = keyof typeof toolGlyphs\n")
	check(os.WriteFile(os.Args[4], []byte(b.String()), 0o644))
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func lum(img image.Image, x, y int) float64 {
	r, g, b, _ := img.At(x, y).RGBA()
	return (0.299*float64(r) + 0.587*float64(g) + 0.114*float64(b)) / 257
}

// outside is the signed distance of a window point to the border box: negative inside.
func edgeDistance(x, y float64) float64 {
	cx, cy := boxX+boxSize/2, boxY+boxSize/2
	half := boxSize / 2
	qx := math.Abs(x-cx) - (half - corner)
	qy := math.Abs(y-cy) - (half - corner)
	return math.Hypot(math.Max(qx, 0), math.Max(qy, 0)) + math.Min(math.Max(qx, qy), 0) - corner
}

func trace(img image.Image, left, top int) string {
	// Normalise the glyph between the button's background and its peak.
	var inner []float64
	valid := make([][]bool, window)
	raw := make([][]float64, window)
	for j := 0; j < window; j++ {
		valid[j] = make([]bool, window)
		raw[j] = make([]float64, window)
		for i := 0; i < window; i++ {
			raw[j][i] = lum(img, left+i, top+j)
			valid[j][i] = edgeDistance(float64(i)+0.5, float64(j)+0.5) < -ringWidth
			if valid[j][i] {
				inner = append(inner, raw[j][i])
			}
		}
	}
	bg := buttonBackground
	sorted := append([]float64(nil), inner...)
	sort.Float64s(sorted)
	peak := sorted[len(sorted)*995/1000]
	if peak-bg < 8 {
		return ""
	}
	norm := func(i, j int) float64 {
		if i < 0 || j < 0 || i >= window || j >= window || !valid[j][i] {
			return 0
		}
		return math.Max(0, math.Min(1, (raw[j][i]-bg)/(peak-bg)))
	}

	// Bilinear samples at the corners of the upsampled grid; pixel centres sit at i+0.5.
	n := window * scale
	grid := make([][]float64, n+1)
	for Y := 0; Y <= n; Y++ {
		grid[Y] = make([]float64, n+1)
		fy := float64(Y)/scale - 0.5
		j0 := int(math.Floor(fy))
		ty := fy - float64(j0)
		for X := 0; X <= n; X++ {
			fx := float64(X)/scale - 0.5
			i0 := int(math.Floor(fx))
			tx := fx - float64(i0)
			top := norm(i0, j0)*(1-tx) + norm(i0+1, j0)*tx
			bot := norm(i0, j0+1)*(1-tx) + norm(i0+1, j0+1)*tx
			grid[Y][X] = top*(1-ty) + bot*ty
		}
	}

	loops := contours(grid, n)
	var sb strings.Builder
	for _, loop := range loops {
		pts := simplify(loop)
		if len(pts) < 3 {
			continue
		}
		for k, p := range pts {
			op := "L"
			if k == 0 {
				op = "M"
			}
			sb.WriteString(op)
			sb.WriteString(num(p.x))
			sb.WriteString(" ")
			sb.WriteString(num(p.y))
		}
		sb.WriteString("Z")
	}
	return sb.String()
}

func num(v float64) string {
	s := strconv.FormatFloat(math.Round(v*100)/100, 'f', 2, 64)
	s = strings.TrimRight(strings.TrimRight(s, "0"), ".")
	if s == "-0" || s == "" {
		return "0"
	}
	return s
}

// contours runs marching squares over the grid and chains the segments into closed loops. A segment
// end is identified by the grid edge it lies on, so that neighbouring cells join exactly.
func contours(grid [][]float64, n int) [][]point {
	type edge struct {
		x, y int
		h    bool // horizontal edge from (x,y) to (x+1,y); otherwise vertical from (x,y) to (x,y+1)
	}
	at := func(x, y int) float64 { return grid[y][x] }
	cross := func(e edge) point {
		if e.h {
			a, b := at(e.x, e.y), at(e.x+1, e.y)
			return point{(float64(e.x) + (level-a)/(b-a)) / scale, float64(e.y) / scale}
		}
		a, b := at(e.x, e.y), at(e.x, e.y+1)
		return point{float64(e.x) / scale, (float64(e.y) + (level-a)/(b-a)) / scale}
	}
	type segment struct{ a, b edge }
	var segments []segment
	for y := 0; y < n; y++ {
		for x := 0; x < n; x++ {
			v := [4]float64{at(x, y), at(x+1, y), at(x+1, y+1), at(x, y+1)}
			idx := 0
			for k := 0; k < 4; k++ {
				if v[k] >= level {
					idx |= 1 << k
				}
			}
			if idx == 0 || idx == 15 {
				continue
			}
			top := edge{x, y, true}
			right := edge{x + 1, y, false}
			bottom := edge{x, y + 1, true}
			left := edge{x, y, false}
			centre := (v[0]+v[1]+v[2]+v[3])/4 >= level
			switch idx {
			case 1, 14:
				segments = append(segments, segment{left, top})
			case 2, 13:
				segments = append(segments, segment{top, right})
			case 3, 12:
				segments = append(segments, segment{left, right})
			case 4, 11:
				segments = append(segments, segment{right, bottom})
			case 6, 9:
				segments = append(segments, segment{top, bottom})
			case 7, 8:
				segments = append(segments, segment{left, bottom})
			case 5:
				if centre {
					segments = append(segments, segment{left, bottom}, segment{top, right})
				} else {
					segments = append(segments, segment{left, top}, segment{right, bottom})
				}
			case 10:
				if centre {
					segments = append(segments, segment{left, top}, segment{right, bottom})
				} else {
					segments = append(segments, segment{left, bottom}, segment{top, right})
				}
			}
		}
	}

	// Chain: every edge has two segment ends.
	ends := map[edge][]int{}
	for i, s := range segments {
		ends[s.a] = append(ends[s.a], i)
		ends[s.b] = append(ends[s.b], i)
	}
	used := make([]bool, len(segments))
	var loops [][]point
	for start := range segments {
		if used[start] {
			continue
		}
		used[start] = true
		first := segments[start].a
		cur := segments[start].b
		loop := []point{cross(first), cross(cur)}
		for cur != first {
			next := -1
			for _, i := range ends[cur] {
				if !used[i] {
					next = i
					break
				}
			}
			if next < 0 {
				break
			}
			used[next] = true
			if segments[next].a == cur {
				cur = segments[next].b
			} else {
				cur = segments[next].a
			}
			loop = append(loop, cross(cur))
		}
		loops = append(loops, loop)
	}
	return loops
}

// simplify reduces a closed loop with Douglas-Peucker; the loop is split at its two farthest
// points so that the closing edge is treated like any other.
func simplify(loop []point) []point {
	if len(loop) > 1 && loop[0] == loop[len(loop)-1] {
		loop = loop[:len(loop)-1]
	}
	if len(loop) < 4 {
		return loop
	}
	a, b := 0, 0
	best := -1.0
	for i := range loop {
		d := math.Hypot(loop[i].x-loop[0].x, loop[i].y-loop[0].y)
		if d > best {
			best, a = d, i
		}
	}
	best = -1.0
	for i := range loop {
		d := math.Hypot(loop[i].x-loop[a].x, loop[i].y-loop[a].y)
		if d > best {
			best, b = d, i
		}
	}
	if a > b {
		a, b = b, a
	}
	first := douglas(loop[a : b+1])
	second := douglas(append(append([]point{}, loop[b:]...), loop[:a+1]...))
	out := append([]point{}, first[:len(first)-1]...)
	out = append(out, second[:len(second)-1]...)
	return out
}

func douglas(pts []point) []point {
	if len(pts) < 3 {
		return pts
	}
	first, last := pts[0], pts[len(pts)-1]
	maxD, idx := 0.0, 0
	for i := 1; i < len(pts)-1; i++ {
		if d := segDistance(pts[i], first, last); d > maxD {
			maxD, idx = d, i
		}
	}
	if maxD <= tolerance {
		return []point{first, last}
	}
	left := douglas(pts[:idx+1])
	right := douglas(pts[idx:])
	return append(left[:len(left)-1], right...)
}

func segDistance(p, a, b point) float64 {
	dx, dy := b.x-a.x, b.y-a.y
	if dx == 0 && dy == 0 {
		return math.Hypot(p.x-a.x, p.y-a.y)
	}
	t := ((p.x-a.x)*dx + (p.y-a.y)*dy) / (dx*dx + dy*dy)
	t = math.Max(0, math.Min(1, t))
	return math.Hypot(p.x-(a.x+t*dx), p.y-(a.y+t*dy))
}
